package dev.racelab.domain.model;

public enum EventType {
    EXPERIMENT_CREATED,
    EXPERIMENT_STARTED,
    DATA_PREPARED,
    TRANSACTION_STARTED,
    READ_STARTED,
    READ_COMPLETED,
    VALIDATION_STARTED,
    VALIDATION_COMPLETED,
    LOCK_REQUESTED,
    LOCK_ACQUIRED,
    LOCK_WAITING,
    LOCK_RELEASED,
    WRITE_STARTED,
    WRITE_COMPLETED,
    COMMIT_STARTED,
    COMMIT_COMPLETED,
    ROLLBACK_STARTED,
    ROLLBACK_COMPLETED,
    DEADLOCK_DETECTED,
    OPTIMISTIC_LOCK_CONFLICT,
    SERIALIZATION_FAILURE,
    RETRY_SCHEDULED,
    INCONSISTENCY_DETECTED,
    CHECKPOINT_REACHED,
    CHECKPOINT_RELEASED,
    MESSAGE_PUBLISHED,
    MESSAGE_CONSUMED,
    FAULT_INJECTED,
    EXPERIMENT_COMPLETED,
    EXPERIMENT_FAILED,
    EXPERIMENT_CANCELLED;

    public boolean isTerminal() {
        return this == EXPERIMENT_COMPLETED || this == EXPERIMENT_FAILED || this == EXPERIMENT_CANCELLED;
    }
}
